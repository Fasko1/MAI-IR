def format_bytes(value: float) -> str:
    """
    Преобразует размер в байтах в удобный формат:
    Б, КБ, МБ, ГБ, ТБ.
    """

    units = [
        "Б",
        "КБ",
        "МБ",
        "ГБ",
        "ТБ",
    ]

    size = float(value)

    # Пока размер >= 1024, делим его на 1024
    # и переходим к следующей единице измерения.
    for unit in units:
        if size < 1024:
            return f"{size:.2f} {unit}"

        size /= 1024

    # Если размер оказался больше терабайта.
    return f"{size:.2f} ПБ"


# ============================================================
# ГЛАВНАЯ ФУНКЦИЯ АНАЛИЗА КОРПУСА
# ============================================================

def main(config_path: str) -> None:

    # Читаем config.yaml.
    config = load_config(config_path)

    # Подключаемся к PostgreSQL.
    conn = connect(config)

    try:
        # Через cursor выполняются SQL-запросы.
        with conn.cursor() as cursor:

            # =================================================
            # ОБЩАЯ СТАТИСТИКА КОРПУСА
            # =================================================

            cursor.execute(
                """
                SELECT
                    -- Общее количество документов.
                    COUNT(*),

                    -- Суммарный размер сырого HTML в байтах.
                    COALESCE(
                        SUM(
                            OCTET_LENGTH(html)
                        ),
                        0
                    ),

                    -- Средний размер одного HTML-документа.
                    COALESCE(
                        AVG(
                            OCTET_LENGTH(html)
                        ),
                        0
                    ),

                    -- Суммарный размер очищенного текста.
                    COALESCE(
                        SUM(
                            OCTET_LENGTH(
                                clean_text
                            )
                        ),
                        0
                    ),

                    -- Средний размер очищенного текста
                    -- одного документа.
                    COALESCE(
                        AVG(
                            OCTET_LENGTH(
                                clean_text
                            )
                        ),
                        0
                    )

                FROM documents;
                """
            )

            # SQL-запрос возвращает одну строку с 5 значениями.
            # Сразу раскладываем их по переменным.
            (
                document_count,
                total_html_size,
                avg_html_size,
                total_text_size,
                avg_text_size,
            ) = cursor.fetchone()


            # =================================================
            # СТАТИСТИКА ПО ИСТОЧНИКАМ
            # =================================================

            cursor.execute(
                """
                SELECT
                    source,
                    COUNT(*)

                FROM documents

                -- Группируем документы по источнику.
                GROUP BY source

                -- Сортируем источники по названию.
                ORDER BY source;
                """
            )

            # Получаем все строки результата.
            # Например:
            # [("Биомолекула", 550),
            #  ("Техинсайдер", 550)]
            source_stats = cursor.fetchall()

    finally:
        # Соединение закрывается даже если выше возникнет ошибка.
        conn.close()


    # ============================================================
    # ВЫВОД РЕЗУЛЬТАТОВ
    # ============================================================

    print(
        "\n=== Статистика корпуса ===\n"
    )

    print(
        f"Количество документов: "
        f"{document_count}"
    )

    # Размер переводится из байтов в КБ/МБ/ГБ
    # функцией format_bytes().
    print(
        f"Размер сырых данных: "
        f"{format_bytes(total_html_size)}"
    )

    print(
        f"Средний размер документа: "
        f"{format_bytes(avg_html_size)}"
    )

    print(
        f"Размер выделенного текста: "
        f"{format_bytes(total_text_size)}"
    )

    print(
        f"Средний объём текста: "
        f"{format_bytes(avg_text_size)}"
    )

    print(
        "\nДокументы по источникам:"
    )

    # Выводим количество документов отдельно для каждого сайта.
    for source, count in source_stats:
        print(
            f"  {source}: {count}"
        )


