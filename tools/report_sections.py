def report_pdf():
    candidates = [ROOT / name for name in ("report.pdf", "report_unified.pdf") if (ROOT / name).exists()]
    return max(candidates, key=lambda path: path.stat().st_mtime) if candidates else ROOT / "report.pdf"


def prefix(stats, table, screenshot, num):
    source = (ROOT / "tools/project/templates/labs01_02.tex").read_text(encoding="utf-8")
    extra = [(name, num(count), TOPICS.get(name, "Наука и технологии"))
             for name, count in sorted(stats["sources"].items(), key=lambda row: -row[1])
             if name not in ("Биомолекула", "Техинсайдер")]
    additions = (r"\sub{Дополнительные источники корпуса}" + "\n"
        + "Помимо двух основных источников, корпус включает научно-популярные и технические издания. "
          "Распределение документов и основные направления дополнительных источников приведены в таблице.\n"
        + table("Дополнительные источники корпуса", ["Источник", "Документов", "Основное направление"], extra, widths=["l", "r", "X"])
        + "Каждый из перечисленных источников связан с общей тематикой корпуса --- наукой и технологиями --- через своё направление. "
          "Научно-популярные издания освещают исследования, природу и космос; технические площадки --- электронику, программирование и информационную безопасность. "
          "Энциклопедические статьи дополняют эти материалы справочными сведениями. Тематическая связь имеет разную степень: "
          "корпус включает как специальные статьи, так и новости и обзоры из смежных областей.\n")
    corpus = table("Характеристики корпуса документов", ["Показатель", "Значение"], [
        ("Количество документов", num(stats["documents"])),
        ("Количество источников", len(stats["sources"])),
        ("Объём выделенного UTF-8 текста, ГБ", num(stats["text_bytes"] / 1e9, 3)),
        ("Средний объём текста документа, байт", num(stats["text_bytes"] / stats["documents"])),
        ("Среднее число токенов на документ", num(stats["tokens"] / stats["documents"], 1)),
        ("Документы «Биомолекулы»", num(stats["sources"]["Биомолекула"])),
        ("Документы TechInsider", num(stats["sources"]["Техинсайдер"])),
        ("Дата измерений", stats["date"]),
    ]) + screenshot("lab01_corpus", "Статистика корпуса документов")
    robot = ("Проверки охватывают нормализацию URL, извлечение текста и метаданных, сохранение очереди, "
             "продолжение обработки, сетевые отказы и ограничения источников. Изолированные автотесты сборщика "
             "включены в общий запуск; результаты сохранены в \code{tests/results/collection.txt}. "
             "Состояние документов и очереди можно проверить отдельно от сетевой загрузки.\n")
    for name, caption in (
        ("lab02_config", "Пример параметров базового робота: подключение и обход двух источников"),
        ("lab02_run", "Фрагмент сохранённого журнала сбора документов"),
        ("lab02_database", "Документ и его метаданные в PostgreSQL"),
        ("lab02_resume", "Остановка и продолжение работы с сохранённой очередью"),
        ("lab02_update", "Повторная проверка трёх статей: одна запись обновлена"),
    ):
        robot += screenshot(name, caption)
    robot += ("Счётчики в журналах отражают состояние сбора в PostgreSQL. Поисковый индекс построен по отдельному "
              "согласованному снимку из 992 743 документов; продолжение сбора не изменяет готовый индекс автоматически.\n")
    for marker, replacement in {
        "%%ADDITIONAL_SOURCES%%": additions,
        "%%CORPUS_STATS%%": corpus,
        "%%ROBOT_RESULTS%%": robot,
        "%%SOURCE_SEARCH_BIOMOLECULA%%": screenshot("lab01_search_biomolecula", "Поиск по «Биомолекуле» в Яндексе"),
        "%%SOURCE_SEARCH_TECHINSIDER%%": screenshot("lab01_search_techinsider", "Поиск по TechInsider в Яндексе"),
    }.items():
        source = source.replace(marker, replacement)
    return source
