"""Разделы ЛР4/10/12/14 единого отчёта по измерениям полного прогона."""
import json
import hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def add_sections(body,table,num,screenshot):
    """Добавить новые ЛР к общему отчёту; измерения доступны и без больших данных.

    Локально размеры сверяются с файлами. В клоне репозитория используются
    размеры из итогового протокола выполненного прогона.
    """
    folder=ROOT/'results/advanced'
    if not (folder/'pipeline.json').exists():
        return body
    state=json.loads((folder/'pipeline.json').read_text(encoding='utf-8'))
    if state.get('current')!='complete':
        return body
    def load(name):
        return json.loads((folder/(name+'.json')).read_text(encoding='utf-8'))
    lemma,index,coords=load('lemmatization'),load('index'),load('coordinates')
    saved_files=load('final_acceptance')['files'] if (folder/'final_acceptance.json').exists() else {}
    def size(path):
        path=Path(path)
        if path.is_file():
            return path.stat().st_size
        relative=path.relative_to(ROOT).as_posix()
        for item in saved_files.values():
            if item['path']==relative:
                return item['bytes']
        for name,item in state['inputs'].items():
            if name.replace('\\','/')==relative:
                return item['bytes']
        raise ValueError('Нет сохранённого размера: '+relative)

    index_path=ROOT/'data/advanced/index.ir'
    if index_path.is_file():
        with index_path.open('rb') as f:
            signature=hashlib.sha256(f.read(96)).hexdigest()
    else:
        # Только оформление сохранённых измерений, не повторное измерение индекса.
        signature=load('skip_benchmark')['index_header_sha256']
    lemma_section=r'''
\section{Лабораторная работа № 4\\«Словарная лемматизация»}
\sub{Метод и реализация}
Словарная лемматизация приводит словоформы к нормальной форме. Подготовка данных читает словоформы и парадигмы OpenCorpora,
а собственный C++ модуль ищет нормальную форму в собственной хеш-таблице. Готовый морфологический анализатор
в поиске не используется. Корпус и запрос обрабатываются одним словарём; неизвестный токен сохраняется.
Если у формы несколько лемм, выбирается первая по алфавиту после приведения ё к е.
Смысл по контексту не определяется: например, «стали» может относиться к стали или глаголу «стать».
Путь к словарю и контрольные суммы приведены в \code{data/morphology/provenance.json};
источник данных --- OpenCorpora, пакет \code{pymorphy3-dicts-ru}. Чтение словарных парадигм при подготовке
данных не подменяет C++ алгоритм нормализации. Программа: \code{src/ir/extensions.cpp}.
\sub{Результаты полного прохода}
'''
    lemma_section+=table('Словарная нормализация полного корпуса',['Показатель','Значение'],[
        ('Документов',num(lemma['documents'])),('Вхождений лемм',num(lemma['tokens'])),
        ('Изменённых вхождений',num(lemma['changed'])),('Словоформ в словаре',num(lemma['forms'])),
        ('Уникальных лемм/сохранённых токенов индекса',num(index['terms'])),
        ('Время прохода, с',num(state['stages']['lemmatization']['seconds'],3)),
    ])
    config_path=ROOT/'data/advanced/index.search.json'
    config=(json.loads(config_path.read_text(encoding='utf-8')) if config_path.is_file()
            else {key:item['path'] for key,item in saved_files.items()})
    parts=[('Сжатый базовый индекс лемм',ROOT/'data/advanced/index.ir'),
           ('Координатные списки',ROOT/config['positions']),
           ('Выбранная таблица прыжков',ROOT/config['skip-index']),
           ('Смещения исходных текстов',ROOT/config['text-offsets'])]
    lemma_section+=table('Расширенный поисковый набор: состав и размер',['Часть','Размер, МБ'],[
        (label,num(size(path)/1e6,3)) for label,path in parts]+[
        ('Полный размер расширенного набора',num(sum(size(path) for _,path in parts)/1e6,3)),
        ('Словарные данные отдельно',num(size(ROOT/config['lemmas'])/1e6,3)),
    ])
    lemma_section+='Общий размер расширенного поискового набора: '+num(sum(size(path) for _,path in parts)/1e9,3)+' ГБ.\\par\n'
    if (folder/'lemma_quality.json').exists() and load('lemma_quality').get('index_header_sha256')==signature:
        quality=load('lemma_quality')
        lemma_section+=r'\sub{Диагностика качества и ограничения}'+'\n'
        lemma_section+='Использованы два фиксированных набора документов с ИИ-разметкой, без независимой человеческой проверки. Это ограниченная диагностика, не оценка всей коллекции. Кандидаты задаются явным OR; веса вычислены на полном корпусе, затем выдача фильтруется до размеченного набора.\n'
        lemma_section+=table('Сравнение стемминга и лемматизации на размеченных наборах',['Запрос / режим','Точность','Полнота','NDCG@5'],[
            (row['query']+' / '+row['mode'],num(row['precision'],3),num(row['recall'],3),num(row['at5']['ndcg'],3)) for row in quality['results']],widths=['X','r','r','r'])
        lemma_section+='Возможные причины различий: нормализация словоформ, омонимия и изменение частот и норм. Эти факторы требуют отдельного анализа; улучшение любого запроса не гарантируется. Для уточнения нужны анализ контекста и независимая разметка.\n'
    lemma_section+=screenshot('lab04_lemmatization','Словарная лемматизация и её контрольные примеры')

    phrase=r'''
\section{Лабораторная работа № 10\\«Цитатный поиск и координаты»}
\sub{Строгое условие совпадения}
Двойные кавычки означают последовательность соседних исходных токенов в одном документе,
в заданном порядке. Регистр нормализуется, пунктуация разделяет токены, служебные слова сохраняются.
Словоформы внутри цитаты не заменяются леммами. Поэтому «кот дом» не совпадает с «кот большой дом»,
«дом кот» или отдельным «кот». Это строгое совпадение токенов, а не пунктуации исходного текста.
Цитата является узлом общего дерева AND/OR/NOT и фильтрует кандидатов до ранжирования.
\sub{Формат и построение}
Координатный индекс хранит для каждого исходного токена документы и позиции его вхождений.
Он строится внешней сортировкой в \code{positions.ir}.
Координата содержит 32 бита номера документа и 32 бита позиции. Заголовок 40 байт задаёт сигнатуру,
привязку к документам и количества; словарь хранит длину термина, его UTF-8 запись, начало и длину списка.
Каждая координата занимает 8 байт, little-endian. Списки k-го слова сдвигаются на k и пересекаются.
Перед вычитанием проверяется позиция: совпадение через границу документов исключено.
Координаты хранятся без сжатия; VB сжимает базовые пары doc/TF. Это ограничение текущей реализации.
'''
    phrase+=table('Координатный индекс',['Показатель','Значение'],[
        ('Документов',num(coords['documents'])),('Исходных терминов',num(coords['surface_terms'])),
        ('Координат',num(coords['occurrences'])),('Временных серий',num(coords['runs'])),
        ('Среднее число координат на исходный термин',num(coords['occurrences']/coords['surface_terms'],3)),
        ('Скорость по входному TSV, КБ/с',num(size(ROOT/'data/corpus/tokens.tsv')/1000/state['stages']['coordinates']['seconds'],3)),
        ('Размер, МБ',num(size(ROOT/'data/advanced/positions.ir')/1e6,3)),
        ('Построение, с',num(state['stages']['coordinates']['seconds'],3)),
    ])
    if (folder/'acceptance.json').exists():
        acceptance=load('acceptance')
        if acceptance.get('passed'):
            phrase+='Сравнены '+num(acceptance['full_result_lists'])+' полных выдач исходного и сжатого вариантов индекса. Для первых '+num(acceptance['quote_verified_original_documents'])+' результатов одной реальной цитаты независимо проверено наличие соседних токенов в исходных статьях. HTTP-проверки подтверждают вывод сниппетов и пустой ответ для цитаты с отсутствующим словом.\n'
    if (folder/'coordinate_audit.json').exists():
        audit=load('coordinate_audit')
        phrase+='Независимый блочный аудит проверил все координаты: порядок, границы документов и позиций, итоговое количество. Пар «поверхностный термин–документ»: '+num(audit['term_document_pairs'])+'; среднее число позиций на такую пару: '+num(audit['mean_coordinates_per_pair'],3)+'. Аудит не заменяет C++ поиск и читает только ограниченный блок готовых данных.\n'
    phrase+=screenshot('lab10_phrase','Строгая цитата в веб-поиске')

    skip=r'''
\section{Лабораторная работа № 12\\«Прыжки по индексу»}
\sub{Метод и дополнительные поля}
Для длинных обратных списков сохраняется таблица точек перезапуска декодера. Каждая точка содержит
doc-ID, предыдущий doc-ID, порядковый номер постинга и байтовое смещение: четыре поля по 8 байт.
Предыдущий ID позволяет восстановить разности после прыжка. Таблица связана с контрольной суммой базового индекса.
Пересечение читает короткий список и ищет последнюю точку длинного списка, не превосходящую целевой ID.
Пропущенные постинги не декодируются. Списки короче 256 элементов обходятся обычным способом.
Специализация применяется к AND двух терминов; сложные подвыражения корректно вычисляются общим алгоритмом.
DF --- число документов с термином. Сравниваются фиксированные шаги и шаг по корню из DF.
'''
    if (folder/'skip_benchmark.json').exists() and load('skip_benchmark').get('index_header_sha256')==signature:
        bench=load('skip_benchmark')
        skip+=table('Выбор шага по обучающему пулу и проверка на другом пуле',['Шаг','Размер, МБ','Обучение, мс','Проверка, мс'],[
            ('корень из DF' if r['step']==0 else str(r['step']),num(r['bytes']/1e6,3),num(r['train_seconds']*1000,3),num(r['test_seconds']*1000,3)) for r in bench['variants']],widths=['X','r','r','r'])
        skip+='Выполнено пять измерений после прогревочного повторения. Время загрузки индекса исключено. Шаг выбирался только по обучающим запросам; второй пул не участвовал в выборе. Отношение времени без прыжков к времени выбранного варианта: на обучении '+num(bench['train_speedup'],3)+', на проверке '+num(bench['test_speedup'],3)+'. Значение меньше единицы означает замедление, а не ускорение. Полные количества и первые 50 упорядоченных результатов совпали.\n'
    skip+='Сжатый блок читается один раз в буфер, прыжки пропускают декодирование, а не чтение диапазонов диска. Метаданные до 16 списков кешируются в пределах около 67,11 МБ. При слишком частых совпадениях стоимость выбора точки может превысить пользу пропуска. Поэтому результат зависит от соотношения длин списков и распределения ID; универсальное ускорение не обещается.\n'
    skip+=screenshot('lab12_skips','Измерения прыжков и сравнение с обычным пересечением')

    snippet=r'''
\section{Лабораторная работа № 14\\«Построение сниппетов»}
Для документов текущей страницы выбирается окно до 36 токенов и 280 символов с наибольшим числом совпадений.
Исходная статья читается по таблице байтовых смещений, без повторного прохода по всему корпусу.
Совпадения определяются общей нормализацией запроса и документа, но выводится исходный текст со словоформами.
Отрицательные термины не подсвечиваются. Если положительных терминов нет, выводится начало статьи.
Обрезка контекста отмечается многоточием. C++ выдаёт части текста и признаки совпадения в JSON;
веб сначала экранирует каждую часть, затем добавляет собственную подсветку mark.
Это исключает исполнение HTML из статьи. Сниппет не меняет отбор или score.
Ограничения: окно не является смысловым рефератом, повтор одного слова может вытеснить более разнообразный контекст;
обрезка по 280 символам может прервать последнее слово; веб дополнительно ограничен тремя строками.
Если начало окна приближается к совпадению, его конец не расширяется: иногда контекста получается мало.
Тесты проверяют исходные словоформы, подсветку и экранирование опасного HTML.
'''
    snippet+=screenshot('lab14_snippets','Сниппеты исходного текста с подсветкой совпадений')
    for number,section in [(5,lemma_section),(11,phrase),(13,skip),(17,snippet)]:
        marker=r'\section{Лабораторная работа № '+str(number)
        body=body.replace(marker,section+'\n'+marker,1)
    return body
